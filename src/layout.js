export function applyLayout(scene) {
  for (const [path, m] of Object.entries(LAYOUT)) {
    let o = scene;
    for (const name of path.split('/')) o = o?.children.find((c) => c.name === name);
    if (!o) continue;
    o.matrix.fromArray(m);
    o.matrix.decompose(o.position, o.quaternion, o.scale);
  }
}
